_XBallGauge::_XBallGauge()
{
	m_Level = 0;
	m_LevelPercentage = 0;

	m_TextureIndex1	  = -1;
	m_pTextureArchive = NULL;
	m_TooltipCallbackFunc = NULL;

	m_fLeft		= 73.0f;
	m_fTop		= 73.0f;
	m_fRight	= 106.0f;
	m_fBottom	= 106.0f;
}

_XBallGauge::~_XBallGauge()
{

}

void _XBallGauge::SetGaugeColor( D3DCOLOR color )
{	
	int i = 0 ; for(  i = 0; i < (_XDEF_GAUGELINECOUNT<<1); i++ )
	{
		g_LINETABLEVERTEX[i].diffuse = color;
	}
}

void _XBallGauge::Render( void )
{
	if( m_Level <= 0 ) return;

	gpDev->SetRenderState(D3DRS_LIGHTING, FALSE);

	gpDev->SetTextureStageState(0, D3DTSS_COLOROP, D3DTOP_SELECTARG1);
	gpDev->SetTextureStageState(0, D3DTSS_COLORARG1, D3DTA_DIFFUSE);

	gpDev->SetRenderState(D3DRS_ALPHABLENDENABLE, TRUE);
	gpDev->SetRenderState(D3DRS_SRCBLEND,  D3DBLEND_SRCALPHA );
	gpDev->SetRenderState(D3DRS_DESTBLEND, D3DBLEND_INVSRCALPHA  );

	gpDev->SetRenderState( D3DRS_ZENABLE,   D3DZB_FALSE );

	gpDev->SetTexture(0, NULL);	
	gpDev->SetFVF( D3DFVF_INTERFACETVERTEX );
	gpDev->DrawPrimitiveUP(D3DPT_LINELIST, m_Level, g_LINETABLEVERTEX, sizeof(INTERFACETVERTEX));

	gpDev->SetRenderState( D3DRS_ZENABLE, g_RS_UseZBuffer );

	gpDev->SetRenderState(D3DRS_ALPHABLENDENABLE, FALSE);
	gpDev->SetRenderState(D3DRS_LIGHTING, TRUE);
}

void _XBallGauge::DrawToolTip(_XGUIObject*& pfocusobject)
{
	if( m_TooltipCallbackFunc && ( ( pfocusobject == (_XGUIObject*)this ) || !pfocusobject ) )
	{
		ScrnPos* scrnpos = gpInput->GetMouseVirScreenPos();

		if( scrnpos )
		{				
			if( TestAlphaChannel( scrnpos->x, scrnpos->z ) )
			{
				POINT pt = { 0,0 };
				SIZE  size = { 0,0 };
				m_TooltipCallbackFunc( pt, size );
			}
		}
	}
}

void _XBallGauge::SetTexture( _XTextureManager* ptexturearchive, int textureindex1 )
{
	m_TextureIndex1		= textureindex1;	
	m_pTextureArchive	= ptexturearchive;
}

BOOL _XBallGauge::TestAlphaChannel( int x, int y )
{
	if( m_TextureIndex1 == -1 || !m_pTextureArchive ) return FALSE;

	if( (x>(int)m_fLeft) && (x<(int)m_fRight ) && (y>(int)m_fTop ) && (y<(int)m_fBottom) )
	{
		return m_pTextureArchive->TestAlphaChannel( m_TextureIndex1, 
													(x -(int)m_fLeft) , (y - (int)m_fTop) );
	}
	return FALSE;
}
